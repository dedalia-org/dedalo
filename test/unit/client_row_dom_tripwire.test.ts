/**
 * TRIPWIRE — the section/portal ROW DOM: every row view keeps the row invariant,
 * and none of the spellings the row-box redesign removed comes back
 * (WC-2026-10-30-section-record-row-box).
 *
 *   client/dedalo/core/section_record/js/record_window.js   (the one row engine)
 *   client/dedalo/core/section/js/section.js                (window_section_rows, the door)
 *   every view that imports the door or the window, plus the two drag modules
 *   that do not (drag_and_drop.js, render_tool_numisdata_order_coins.js)
 *
 * THE INVARIANT. `content_data.children` holds exactly N `.section_record`
 * elements in index order — `children[i]` is row i with `data-index="i"` — at
 * every N, N=0 included. Nothing else sits in `content_data`: no spacer, no
 * no_records node, no references, no footer; those travel in ONE `.list_after`
 * sibling placed after the list_body (never inside a `role=table`). Rows carry
 * no listener of their own: drag, hover and the TM row action are DELEGATED on
 * content_data / the wrapper, bound to the window's signal.
 *
 * HALVES:
 *  1. OUTCOME (executed). Each in-scope view's REAL `render` runs, full and
 *     content, at N ∈ {0, 3, 201}, on a counting fake DOM: the view module, the
 *     real record window, the real drag binders, the real list_after builders
 *     and the real `common.js` swap execute; every other module the view
 *     imports is an inert stub generated from its export list (a Bun plugin,
 *     this file's own process — an isolated gate). The door is a test double
 *     that hands the rows to the REAL `create_record_window` with a fake row
 *     build. Asserted per view: children === N, all `.section_record`,
 *     `data-index` i at position i, no listener on any row node, and — for every
 *     `layout_table` list_body — `.list_after`'s parent is never the `[role=table]`
 *     element; at N=0 the no-records node (sections) lives in `.list_after`.
 *  2. CENSUS (static, comments stripped). The in-scope set is DERIVED: every
 *     browser module importing `window_section_rows` from section.js or
 *     anything from record_window.js (non-empty, floored, mutation-checked),
 *     plus the two named drag modules. Banned there, zero allowed: the spellings
 *     the redesign deleted (BANNED below, each with a planted positive control).
 *     The record window's import set is the row_window.js constants only.
 *  3. LESS. The row-DOM sheets (derived from the css directories of the in-scope
 *     modules, plus list.less where the table block lives): no `--box_width`, no
 *     `.row_window_spacer` outside the ts_object sheets, no `contents` on
 *     content_data in view_base_section.less, no `subgrid` / `1 / -1` on a row
 *     chain without the `.layout_table` marker, no overflow clip on rows,
 *     content_data or (under `.layout_table`) `.column_section_id`, and z-index
 *     inside a list_body only on the ring `::after` and the named descendants.
 *     The CSS REMOVALS are a later stage of the same redesign: the rules still
 *     violating are banked in LESS_PENDING with their reason, compared EXACTLY
 *     (a new violation reds, and so does a removal left in the bank).
 *  3b. CSS STATE. The COMPILED main.css: a `.layout_table` row (or a row's
 *     direct child) in a state (`:hover`, `:focus-within`, `.dragover`,
 *     `.dragging`, `.selected`) changes paint only — no `content`, `display`,
 *     `position`, `inset` — and every pseudo-element such a rule styles is
 *     generated by a stateless rule (WebKit re-sizes a subgrid row's tracks
 *     alone when a box appears on hover; measured in the WC entry).
 *  4. NO-OP. The `common.js` list_after swap (`place_list_after`) is a strict
 *     no-op for a component with neither pointer, executed on the counting DOM;
 *     its three transitions (insert after list_body, replace, remove) execute
 *     too, and the `common.render('content')` branch calls it.
 *
 * ROW_INVARIANT_EXEMPT is shrink-only, each entry with its reason.
 *
 * HONEST LIMIT. The outcome half runs the views against stubs: it proves the
 * DOM each view hands back, not what a real component renders inside a cell,
 * nor the door's edit safety (test_row_invariant, the browser suite, owns
 * that on real components and the suite database).
 */

