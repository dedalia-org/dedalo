	/** The export names of a module on disk (what a stub of it must provide). */
	const exportNames = (abs: string, seen = new Set<string>()): string[] => {
		const names = new Set<string>();
		if (seen.has(abs)) return [];
		seen.add(abs);
		const body = parseModule(readFileSync(abs, 'utf8')).program.body as AstNode[];
		for (const n of body) {
			if (n.type === 'ExportDefaultDeclaration') names.add('default');
			if (n.type === 'ExportAllDeclaration') {
				const from = resolve(dirname(abs), String(n.source.value));
				if (existsSync(from))
					for (const name of exportNames(from, seen)) if (name !== 'default') names.add(name);
			}
			if (n.type !== 'ExportNamedDeclaration') continue;
			const d = n.declaration;
			if (d?.type === 'VariableDeclaration')
				for (const v of d.declarations) if (v.id?.name) names.add(v.id.name);
			if (d?.id?.name) names.add(d.id.name);
			for (const s of n.specifiers ?? []) names.add(String(s.exported?.name ?? s.exported?.value));
		}
		return [...names];
	};

	/** The names an importer takes from one specifier (for a module not on disk). */
	const importedNames = (importer: string, specifier: string): string[] => {
		const body = parseModule(readFileSync(importer, 'utf8')).program.body as AstNode[];
		const names = new Set<string>();
		for (const n of body) {
			if (n.type !== 'ImportDeclaration' || n.source.value !== specifier) continue;
			for (const s of n.specifiers)
				names.add(
					s.type === 'ImportSpecifier' ? String(s.imported.name ?? s.imported.value) : 'default',
				);
		}
		return [...names];
	};

