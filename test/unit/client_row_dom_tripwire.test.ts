	type LessRule = { file: string; line: number; chain: string; prop: string; value: string };

	/**
	 * A minimal LESS walker: comments stripped, nested selectors joined (`&`
	 * substituted), one record per declaration with its full selector chain.
	 * Mixins, variables and at-rule preludes are carried into the chain as text,
	 * which is all the legs below read.
	 */
	const lessRules = (file: string, source: string): LessRule[] => {
		const text = source.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
		const lines = text.split('\n').map((l) => l.replace(/(^|[^:'"])\/\/.*$/, '$1'));
		const flat = lines.join('\n');
		const out: LessRule[] = [];
		const stack: string[] = [];
		let buf = '';
		let line = 1;
		let bufLine = 1;
		for (const ch of flat) {
			if (ch === '\n') line++;
			if (ch === '{') {
				const sel = buf.trim();
				const parent = stack[stack.length - 1] ?? '';
				const joined = sel.includes('&')
					? sel.replace(/&/g, parent)
					: parent
						? `${parent} ${sel}`
						: sel;
				stack.push(joined);
				buf = '';
				bufLine = line;
			} else if (ch === '}') {
				if (buf.trim()) push(buf);
				stack.pop();
				buf = '';
				bufLine = line;
			} else if (ch === ';') {
				push(buf);
				buf = '';
				bufLine = line;
			} else {
				if (!buf.trim()) bufLine = line;
				buf += ch;
			}
		}
		function push(decl: string) {
			const d = decl.trim();
			const at = d.indexOf(':');
			if (at <= 0 || d.startsWith('@') || d.startsWith('.') || d.startsWith('&')) return;
			out.push({
				file,
				line: bufLine,
				chain: (stack[stack.length - 1] ?? '').replace(/\s+/g, ' '),
				prop: d.slice(0, at).trim(),
				value: d.slice(at + 1).trim(),
			});
		}
		return out;
	};

