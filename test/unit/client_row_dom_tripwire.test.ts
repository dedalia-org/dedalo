	/** A compound selector: tag, #id, .class…, [attr], :not(.class), :scope. */
	type Compound = {
		scope: boolean;
		tag: string | null;
		id: string | null;
		classes: string[];
		attrs: string[];
		not: string[];
	};

	const parseCompound = (text: string): Compound => {
		const c: Compound = { scope: false, tag: null, id: null, classes: [], attrs: [], not: [] };
		let rest = text;
		rest = rest.replace(/:not\(\s*\.([\w-]+)\s*\)/g, (_m, cls: string) => {
			c.not.push(cls);
			return '';
		});
		rest = rest.replace(/:scope/g, () => {
			c.scope = true;
			return '';
		});
		rest = rest.replace(/\[([\w-]+)(?:=[^\]]*)?\]/g, (_m, attr: string) => {
			c.attrs.push(attr);
			return '';
		});
		rest = rest.replace(/:[\w-]+(\([^)]*\))?/g, '');
		const tag = /^[a-zA-Z][\w-]*/.exec(rest);
		if (tag) c.tag = tag[0].toUpperCase();
		for (const m of rest.matchAll(/#([\w-]+)/g)) c.id = m[1] ?? null;
		for (const m of rest.matchAll(/\.([\w-]+)/g)) c.classes.push(m[1] ?? '');
		return c;
	};

	/** `a > b c` → [{compound, combinator-before}] */
	const parseSelector = (selector: string) => {
		const parts: Array<{ compound: Compound; child: boolean }> = [];
		const tokens = selector
			.trim()
			.replace(/\s*>\s*/g, ' > ')
			.split(/\s+/);
		let child = false;
		for (const token of tokens) {
			if (token === '>') {
				child = true;
				continue;
			}
			parts.push({ compound: parseCompound(token), child });
			child = false;
		}
		return parts;
	};

	class FakeElement {
		tagName: string;
		ownerDocument: FakeDocument;
		parentNode: FakeElement | null = null;
		nodeType = 1;
		_children: FakeElement[] = [];
		_classes = new Set<string>();
		_attributes = new Map<string, string>();
		_listeners: Listener[] = [];
		/** addEventListener calls ever made on this node. */
		listener_calls = 0;
		/** DOM mutations ever made on this node (append/insert/remove of a child). */
		mutations = 0;
		_text = '';
		inert = false;
		hidden = false;
		draggable = false;
		style: Record<string, unknown>;
		[key: string]: unknown;
		constructor(doc: FakeDocument, tag: string) {
			this.ownerDocument = doc;
			this.tagName = tag.toUpperCase();
			const store = new Map<string, string>();
			this.style = {
				setProperty: (name: string, value: string) => store.set(name, value),
				getPropertyValue: (name: string) => store.get(name) ?? '',
				removeProperty: (name: string) => store.delete(name),
			};
		}
		get classList() {
			const self = this;
			return {
				add: (...names: string[]) => {
					for (const n of names) if (n) self._classes.add(n);
				},
				remove: (...names: string[]) => {
					for (const n of names) self._classes.delete(n);
				},
				contains: (name: string) => self._classes.has(name),
				toggle: (name: string, force?: boolean) => {
					const on = force ?? !self._classes.has(name);
					if (on) self._classes.add(name);
					else self._classes.delete(name);
					return on;
				},
				get length() {
					return self._classes.size;
				},
				[Symbol.iterator]: () => self._classes.values(),
			};
		}
		get className(): string {
			return [...this._classes].join(' ');
		}
		set className(value: string) {
			this._classes = new Set(String(value).split(/\s+/).filter(Boolean));
		}
		get id(): string {
			return this._attributes.get('id') ?? '';
		}
		set id(value: string) {
			this._attributes.set('id', String(value));
		}
		get children(): FakeElement[] {
			return this._children;
		}
		get childNodes(): FakeElement[] {
			return this._children;
		}
		get childElementCount(): number {
			return this._children.length;
		}
		get firstChild(): FakeElement | null {
			return this._children[0] ?? null;
		}
		get firstElementChild(): FakeElement | null {
			return this._children[0] ?? null;
		}
		get lastChild(): FakeElement | null {
			return this._children[this._children.length - 1] ?? null;
		}
		get nextSibling(): FakeElement | null {
			const p = this.parentNode;
			if (!p) return null;
			return p._children[p._children.indexOf(this) + 1] ?? null;
		}
		get nextElementSibling(): FakeElement | null {
			return this.nextSibling;
		}
		get previousElementSibling(): FakeElement | null {
			const p = this.parentNode;
			if (!p) return null;
			return p._children[p._children.indexOf(this) - 1] ?? null;
		}
		get parentElement(): FakeElement | null {
			return this.parentNode && !(this.parentNode instanceof FakeFragment) ? this.parentNode : null;
		}
		get isConnected(): boolean {
			let node: FakeElement | null = this;
			while (node) {
				if (node === this.ownerDocument.body) return true;
				node = node.parentNode;
			}
			return false;
		}
		get textContent(): string {
			return this._text + this._children.map((c) => c.textContent).join('');
		}
		set textContent(value: string) {
			this._children = [];
			this._text = String(value ?? '');
		}
		get innerHTML(): string {
			return this.textContent;
		}
		set innerHTML(value: string) {
			this.textContent = String(value ?? '').replace(/<[^>]*>/g, '');
		}
		get innerText(): string {
			return this.textContent;
		}
		set innerText(value: string) {
			this.textContent = value;
		}
		get dataset(): Record<string, string> {
			return new Proxy({} as Record<string, string>, {
				get: (_t, key) =>
					this._attributes.get(
						`data-${String(key).replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`,
					),
				set: (_t, key, value) => {
					this._attributes.set(
						`data-${String(key).replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`,
						String(value),
					);
					return true;
				},
				deleteProperty: (_t, key) => {
					this._attributes.delete(`data-${String(key)}`);
					return true;
				},
			});
		}
		setAttribute(name: string, value: string) {
			this._attributes.set(name, String(value));
		}
		getAttribute(name: string): string | null {
			return this._attributes.get(name) ?? null;
		}
		hasAttribute(name: string): boolean {
			return this._attributes.has(name);
		}
		removeAttribute(name: string) {
			this._attributes.delete(name);
		}
		toggleAttribute(name: string, force?: boolean) {
			const on = force ?? !this._attributes.has(name);
			if (on) this._attributes.set(name, '');
			else this._attributes.delete(name);
			return on;
		}
		_detach() {
			if (this.parentNode) {
				const siblings = this.parentNode._children;
				const at = siblings.indexOf(this);
				if (at !== -1) siblings.splice(at, 1);
				this.parentNode.mutations++;
				this.parentNode = null;
			}
		}
		_insert(child: unknown, at: number): void {
			if (!(child instanceof FakeElement)) return; // an inert stub's answer: ignored
			if (child instanceof FakeFragment) {
				const moved = child._children;
				child._children = [];
				for (const [k, node] of moved.entries()) {
					node.parentNode = this;
					this._children.splice(at + k, 0, node);
				}
				this.mutations++;
				return;
			}
			child._detach();
			child.parentNode = this;
			this._children.splice(at, 0, child);
			this.mutations++;
		}
		appendChild(child: FakeElement): FakeElement {
			this._insert(child, this._children.length);
			return child;
		}
		append(...nodes: unknown[]) {
			for (const n of nodes) {
				if (typeof n === 'string') this._text += n;
				else this._insert(n, this._children.length);
			}
		}
		prepend(...nodes: unknown[]) {
			let at = 0;
			for (const n of nodes) {
				if (n instanceof FakeElement) {
					const size = n instanceof FakeFragment ? n._children.length : 1;
					this._insert(n, at);
					at += size;
				}
			}
		}
		insertBefore(child: FakeElement, ref: FakeElement | null): FakeElement {
			const at = ref ? this._children.indexOf(ref) : -1;
			this._insert(child, at === -1 ? this._children.length : at);
			return child;
		}
		after(...nodes: unknown[]) {
			const p = this.parentNode;
			if (!p) return;
			let at = p._children.indexOf(this) + 1;
			for (const n of nodes) {
				if (n instanceof FakeElement) {
					const size = n instanceof FakeFragment ? n._children.length : 1;
					p._insert(n, at);
					at += size;
				}
			}
		}
		before(...nodes: unknown[]) {
			const p = this.parentNode;
			if (!p) return;
			for (const n of nodes) p._insert(n, p._children.indexOf(this));
		}
		replaceWith(node: FakeElement) {
			const parent = this.parentNode;
			if (!parent || !(node instanceof FakeElement)) return;
			node._detach();
			const at = parent._children.indexOf(this);
			parent._children[at] = node;
			node.parentNode = parent;
			this.parentNode = null;
			parent.mutations++;
		}
		replaceChildren(...nodes: unknown[]) {
			for (const c of [...this._children]) c._detach();
			this.append(...nodes);
		}
		remove() {
			this._detach();
		}
		removeChild(child: FakeElement) {
			child._detach();
			return child;
		}
		contains(other: FakeElement | null): boolean {
			let node = other;
			while (node) {
				if (node === this) return true;
				node = node.parentNode;
			}
			return false;
		}
		_matchesCompound(c: Compound, scope: FakeElement | null): boolean {
			if (c.scope && this !== scope) return false;
			if (c.tag && this.tagName !== c.tag) return false;
			if (c.id && this.id !== c.id) return false;
			for (const cls of c.classes) if (!this._classes.has(cls)) return false;
			for (const attr of c.attrs) if (!this._attributes.has(attr)) return false;
			for (const cls of c.not) if (this._classes.has(cls)) return false;
			return true;
		}
		_matchesParts(parts: ReturnType<typeof parseSelector>, scope: FakeElement | null): boolean {
			const last = parts[parts.length - 1];
			if (!last || !this._matchesCompound(last.compound, scope)) return false;
			let node: FakeElement | null = this;
			for (let i = parts.length - 1; i > 0; i--) {
				const part = parts[i];
				const prev = parts[i - 1];
				if (!part || !prev) return false;
				if (part.child) {
					node = node?.parentNode ?? null;
					if (!node?._matchesCompound(prev.compound, scope)) return false;
				} else {
					node = node?.parentNode ?? null;
					while (node && !node._matchesCompound(prev.compound, scope)) node = node.parentNode;
					if (!node) return false;
				}
			}
			return true;
		}
		matches(selector: string): boolean {
			return selector.split(',').some((s) => this._matchesParts(parseSelector(s), null));
		}
		closest(selector: string): FakeElement | null {
			let node: FakeElement | null = this;
			while (node) {
				if (node.matches(selector)) return node;
				node = node.parentElement;
			}
			return null;
		}
		querySelectorAll(selector: string): FakeElement[] {
			const out: FakeElement[] = [];
			const groups = selector.split(',').map((s) => parseSelector(s));
			const walk = (node: FakeElement) => {
				for (const child of node._children) {
					if (groups.some((parts) => child._matchesParts(parts, this))) out.push(child);
					walk(child);
				}
			};
			walk(this);
			return out;
		}
		querySelector(selector: string): FakeElement | null {
			return this.querySelectorAll(selector)[0] ?? null;
		}
		getElementsByClassName(name: string): FakeElement[] {
			return this.querySelectorAll(`.${name}`);
		}
		getBoundingClientRect() {
			return { height: 40, width: 100, top: 0, left: 0, bottom: 40, right: 100, x: 0, y: 0 };
		}
		get offsetHeight() {
			return 40;
		}
		get offsetWidth() {
			return 100;
		}
		get clientHeight() {
			return 40;
		}
		get scrollHeight() {
			return 40;
		}
		focus() {
			this.ownerDocument.activeElement = this;
		}
		blur() {}
		click() {}
		scrollIntoView() {}
		addEventListener(type: string, fn: (event: unknown) => void, options?: unknown) {
			this.listener_calls++;
			const opts =
				typeof options === 'object' && options !== null
					? (options as { signal?: AbortSignal })
					: {};
			if (opts.signal?.aborted) return;
			const listener = { type, fn };
			this._listeners.push(listener);
			opts.signal?.addEventListener('abort', () => {
				this._listeners = this._listeners.filter((l) => l !== listener);
			});
		}
		removeEventListener(type: string, fn: unknown) {
			this._listeners = this._listeners.filter((l) => !(l.type === type && l.fn === fn));
		}
		dispatchEvent(): boolean {
			return true;
		}
		animate() {
			return { finished: Promise.resolve(), cancel() {}, onfinish: null };
		}
	}

