/**
 * THE RETENTION PRUNES ARE BATCHED (T1-24 / audit S17 + D02).
 *
 * The two age-window prunes (matrix_activity — matrix_write.ts
 * pruneMatrixEventRowsByAge; the dd1758 publication ledger — diffusion_delete.ts
 * pruneSettledLedgerRows) used to be ONE `DELETE … WHERE "timestamp" < cutoff`.
 * On a 33 M-row log that statement runs for minutes, so under the request
 * statement ceiling (`DB_STATEMENT_TIMEOUT_MS`) it is rolled back — every day,
 * forever — and the ceiling could not be switched on by default. Owner ruling
 * 2026-11-11: BATCH them (never unbounded).
 *
 * The situation is BUILT, under a REAL ceiling: a child process (the ceiling is
 * frozen at config import — test/helpers/child_driver.ts) with
 * DB_STATEMENT_TIMEOUT_MS=500 and a `BEFORE DELETE` trigger that sleeps 50 ms
 * per row of THIS run's planted rows. Twelve planted rows deleted as ONE
 * statement = 600 ms > 500 ms → `db.statement_timeout` (the HEAD failure); in
 * batches of 4 every step is ~200 ms and the prune completes.
 *
 * Surfaces: the dd1758 table is a `dedalo_ts_test_*` scratch twin
 * (DIFFUSION_ACTIVITY_TABLE seam, dropped after); matrix_activity rows carry a
 * per-run marker and the slow trigger fires only on them (WHEN clause), named
 * per run and dropped after even on failure. Marked suite DB only.
 */

import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import { sql } from '../../src/core/db/postgres.ts';
import { assertTestDatabase } from '../../src/core/test_data/test_database_marker.ts';
import { childDriver, driverResult, repoModule } from '../helpers/child_driver.ts';

const TAG = `zzt124_${process.pid}`;
const LEDGER = `dedalo_ts_test_zzt124_${process.pid}`;
const SLOW_FN = `${TAG}_slow_delete`;
const ACTIVITY_TRIGGER = `${TAG}_activity_slow`;
const LEDGER_TRIGGER = `${TAG}_ledger_slow`;
const CEILING_MS = 500;

interface LegResult {
	ok: boolean;
	value?: Record<string, unknown>;
	error?: { code?: string; message?: string };
}

const DRIVER = `
import { sql } from ${repoModule('src/core/db/postgres.ts')};
import { assertTestDatabase } from ${repoModule('src/core/test_data/test_database_marker.ts')};
import { logActivity } from ${repoModule('src/core/api/handlers/activity_log.ts')};
import { pruneMatrixEventRowsByAge } from ${repoModule('src/core/db/matrix_write.ts')};
import {
	activityTable, DIFFUSION_ACTION, ensureDiffusionActivityTable, logDiffusionActivity, pruneSettledLedgerRows,
} from ${repoModule('src/core/diffusion_bridge/diffusion_delete.ts')};
import { runRetention } from ${repoModule('src/core/retention/registry.ts')};
import ${repoModule('src/core/retention/prune.ts')};
await assertTestDatabase('retention_prune_batched_native');

const TAG = ${JSON.stringify(TAG)};
const LEDGER = ${JSON.stringify(LEDGER)};
const SLOW_FN = ${JSON.stringify(SLOW_FN)};
const ACTIVITY_TRIGGER = ${JSON.stringify(ACTIVITY_TRIGGER)};
const LEDGER_TRIGGER = ${JSON.stringify(LEDGER_TRIGGER)};
if (activityTable() !== LEDGER) throw new Error('dd1758 seam not active: ' + activityTable());

const results = {};
function describeError(e) {
	return { code: e?.code, message: String(e?.message ?? e).slice(0, 400) };
}
async function leg(name, fn) {
	try { results[name] = { ok: true, value: await fn() }; }
	catch (e) { results[name] = { ok: false, error: describeError(e) }; }
}

await sql.unsafe('CREATE OR REPLACE FUNCTION "' + SLOW_FN + '"() RETURNS trigger LANGUAGE plpgsql AS $f$ BEGIN PERFORM pg_sleep(0.05); RETURN OLD; END $f$', []);

/** A fresh scratch ledger with the slow trigger on every row. */
async function freshLedger() {
	await sql.unsafe('DROP TABLE IF EXISTS "' + LEDGER + '"', []);
	await sql.unsafe('DROP SEQUENCE IF EXISTS "' + LEDGER + '_section_id_seq"', []);
	// The module latch remembers the first creation; re-create by hand the same way.
	await sql.unsafe('CREATE SEQUENCE "' + LEDGER + '_section_id_seq"', []);
	await sql.unsafe('CREATE TABLE "' + LEDGER + '" (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "timestamp" timestamp without time zone DEFAULT now(), section_id integer NOT NULL DEFAULT nextval(\\'' + LEDGER + '_section_id_seq\\'), section_tipo character varying(255) NOT NULL, data jsonb, relation jsonb, string jsonb, date jsonb, iri jsonb, geo jsonb, number jsonb, media jsonb, misc jsonb, relation_search jsonb, meta jsonb)', []);
	await ensureDiffusionActivityTable();
}
async function slowLedger() {
	await sql.unsafe('CREATE TRIGGER "' + LEDGER_TRIGGER + '" BEFORE DELETE ON "' + LEDGER + '" FOR EACH ROW EXECUTE FUNCTION "' + SLOW_FN + '"()', []);
}
/** Plant settled (published) and pending rows, then age the first ones. */
async function plantLedger(settledAged, pendingAged, fresh) {
	let id = 1000;
	for (let i = 0; i < settledAged + pendingAged; i++) {
		// Interleave: every 4th aged row is pending debt.
		const pending = pendingAged > 0 && i % 4 === 3 && i / 4 < pendingAged;
		await logDiffusionActivity({ sectionTipo: 'zzt124', sectionId: id++, elementTipo: null,
			action: pending ? DIFFUSION_ACTION.unpublishPending : DIFFUSION_ACTION.published });
	}
	await sql.unsafe('UPDATE "' + LEDGER + '" SET "timestamp" = now() - interval \\'400 days\\' - (id * interval \\'1 second\\')', []);
	for (let i = 0; i < fresh; i++) {
		await logDiffusionActivity({ sectionTipo: 'zzt124', sectionId: id++, elementTipo: null, action: DIFFUSION_ACTION.published });
	}
}
async function ledgerCounts() {
	const rows = await sql.unsafe('SELECT count(*) FILTER (WHERE "timestamp" < now() - interval \\'365 days\\')::int AS aged, count(*)::int AS total FROM "' + LEDGER + '"', []);
	return rows[0];
}
try {
	// LEG ledger_ceiling: 12 settled aged (+3 pending aged interleaved, +2 fresh),
	// dry then apply in batches of 4, all under the 500 ms ceiling.
	await leg('ledger_ceiling', async () => {
		await freshLedger();
		await plantLedger(12, 3, 2);
		await slowLedger();
		const dry = await pruneSettledLedgerRows({ windowDays: 365, apply: false, batchRows: 4 });
		const afterDry = await ledgerCounts();
		const applied = await pruneSettledLedgerRows({ windowDays: 365, apply: true, batchRows: 4 });
		const left = await ledgerCounts();
		return { dry, afterDry, applied, left };
	});

	// LEG ledger_registry: the same through the retention registry (the seam threads).
	await leg('ledger_registry', async () => {
		await freshLedger();
		await plantLedger(12, 3, 2);
		await slowLedger();
		const report = await runRetention('diffusion_publication_ledger', { apply: true, batchRows: 4 });
		const left = await ledgerCounts();
		return { report, left };
	});

	// LEG keyset_exact: timestamp TIES (id tie-break) and 1 µs-apart rows across
	// batch boundaries — dry count == apply deletion == planted, batches of 2.
	await leg('keyset_exact', async () => {
		await freshLedger();
		for (let i = 0; i < 7; i++) {
			await logDiffusionActivity({ sectionTipo: 'zzt124', sectionId: 2000 + i, elementTipo: null, action: DIFFUSION_ACTION.published });
		}
		// ids 1..7 → three share one instant, then pairs 1 µs apart.
		await sql.unsafe('UPDATE "' + LEDGER + '" SET "timestamp" = timestamp \\'2001-01-01 00:00:00.000001\\' + (CASE WHEN id <= 3 THEN 0 WHEN id <= 5 THEN 1 ELSE 2 END) * interval \\'1 microsecond\\'', []);
		const dry = await pruneSettledLedgerRows({ windowDays: 365, apply: false, batchRows: 2 });
		const applied = await pruneSettledLedgerRows({ windowDays: 365, apply: true, batchRows: 2 });
		const left = await ledgerCounts();
		return { dry, applied, left };
	});

	// LEG abort: the signal fires while batch 2 runs; the loop stops after the
	// in-flight batch commits — what it removed stays removed, the rest is intact.
	await leg('abort', async () => {
		await freshLedger();
		await plantLedger(12, 0, 0);
		await slowLedger();
		const controller = new AbortController();
		setTimeout(() => controller.abort(), 300);
		const applied = await pruneSettledLedgerRows({ windowDays: 365, apply: true, batchRows: 4, signal: controller.signal });
		const left = await ledgerCounts();
		return { applied, left };
	});

	// LEG activity_ceiling: matrix_activity, 12 marked aged rows + 1 marked fresh.
	await leg('activity_ceiling', async () => {
		for (let i = 0; i < 13; i++) {
			await logActivity({ what: 'LOG IN', tipo: 'dd229', userId: -666, host: 'localhost', data: { msg: TAG + '_' + (i < 12 ? 'aged' : 'fresh') + '_' + i } });
		}
		await sql.unsafe("UPDATE matrix_activity SET \\"timestamp\\" = now() - interval '400 days' WHERE section_tipo = 'dd542' AND misc::text LIKE $1", ['%' + TAG + '_aged_%']);
		const marked = async () => (await sql.unsafe("SELECT count(*) FILTER (WHERE misc::text LIKE $1)::int AS aged, count(*) FILTER (WHERE misc::text LIKE $2)::int AS fresh FROM matrix_activity WHERE section_tipo = 'dd542' AND misc::text LIKE $3", ['%' + TAG + '_aged_%', '%' + TAG + '_fresh_%', '%' + TAG + '%']))[0];
		const before = await marked();
		await sql.unsafe('CREATE TRIGGER "' + ACTIVITY_TRIGGER + '" BEFORE DELETE ON matrix_activity FOR EACH ROW WHEN (OLD.misc::text LIKE \\'%' + TAG + '_%\\') EXECUTE FUNCTION "' + SLOW_FN + '"()', []);
		const cut = new Date(Date.now() - 365 * 24 * 60 * 60 * 1000).toISOString();
		const applied = await pruneMatrixEventRowsByAge('matrix_activity', cut, { apply: true, batchRows: 4 });
		const after = await marked();
		return { before, applied, after };
	});
} finally {
	await sql.unsafe('DROP TRIGGER IF EXISTS "' + ACTIVITY_TRIGGER + '" ON matrix_activity', []);
	await sql.unsafe("DELETE FROM matrix_activity WHERE section_tipo = 'dd542' AND misc::text LIKE $1", ['%' + TAG + '%']);
	await sql.unsafe('DROP TABLE IF EXISTS "' + LEDGER + '"', []);
	await sql.unsafe('DROP SEQUENCE IF EXISTS "' + LEDGER + '_section_id_seq"', []);
	await sql.unsafe('DROP FUNCTION IF EXISTS "' + SLOW_FN + '"()', []);
}
console.log('RESULT ' + JSON.stringify(results));
process.exit(0);
`;

const driver = childDriver('dedalo-retention-batched');
let legs: Record<string, LegResult> = {};

/** Belt and braces: the driver cleans up in `finally`; this covers a killed child. */
async function sweep(): Promise<void> {
	await sql.unsafe(`DROP TRIGGER IF EXISTS "${ACTIVITY_TRIGGER}" ON matrix_activity`, []);
	await sql.unsafe(
		`DELETE FROM matrix_activity WHERE section_tipo = 'dd542' AND misc::text LIKE $1`,
		[`%${TAG}%`],
	);
	await sql.unsafe(`DROP TABLE IF EXISTS "${LEDGER}"`, []);
	await sql.unsafe(`DROP SEQUENCE IF EXISTS "${LEDGER}_section_id_seq"`, []);
	await sql.unsafe(`DROP FUNCTION IF EXISTS "${SLOW_FN}"()`, []);
}

beforeAll(async () => {
	await assertTestDatabase('retention_prune_batched_native');
	await sweep();
	const { stdout, stderr } = await driver.run('retention_driver.ts', DRIVER, {
		DB_STATEMENT_TIMEOUT_MS: String(CEILING_MS),
		DIFFUSION_ACTIVITY_TABLE: LEDGER,
		DEDALO_DIFFUSION_LEDGER_RETENTION_DAYS: '365',
	});
	legs = driverResult<Record<string, LegResult>>(stdout, stderr);
}, 180_000);

afterAll(async () => {
	await sweep();
	driver.dispose();
}, 60_000);

function value(name: string): Record<string, unknown> {
	const result = legs[name];
	expect(result, `leg ${name} missing`).toBeDefined();
	if (result?.ok !== true) {
		throw new Error(`leg ${name} threw: ${JSON.stringify(result?.error)}`);
	}
	return result.value as Record<string, unknown>;
}

type Counts = { aged: number; total: number };
type LedgerReport = { candidates: number; deleted: number; detail: Record<string, unknown> };

describe('retention prunes run in committed keyset batches (T1-24 / S17)', () => {
	test('the dd1758 prune completes under a real statement ceiling; pending debt and fresh rows survive', () => {
		const leg = value('ledger_ceiling');
		const dry = leg.dry as LedgerReport;
		const applied = leg.applied as LedgerReport;
		// Dry: the same predicate, batched, writes nothing.
		expect(dry.candidates).toBe(12);
		expect(dry.deleted).toBe(0);
		expect((leg.afterDry as Counts).total).toBe(17);
		// Apply: 12 settled aged rows gone in 4 steps of ≤4 (the 4th sees 0 → stop).
		expect(applied.deleted).toBe(12);
		expect(applied.detail.batches).toBe(4);
		expect(applied.detail.batch_rows).toBe(4);
		expect(applied.detail.stopped).toBeNull();
		// 3 pending aged rows (outstanding debt) + 2 fresh rows remain.
		const left = leg.left as Counts;
		expect(left.total).toBe(5);
		expect(left.aged).toBe(3);
	});

	test('the retention registry threads batchRows to the ledger prune', () => {
		const leg = value('ledger_registry');
		const report = leg.report as LedgerReport;
		expect(report.deleted).toBe(12);
		expect(report.detail.batch_rows).toBe(4);
		expect((leg.left as Counts).total).toBe(5);
	});

	test('the keyset cursor neither skips nor repeats rows across timestamp ties and µs steps', () => {
		const leg = value('keyset_exact');
		const dry = leg.dry as LedgerReport;
		const applied = leg.applied as LedgerReport;
		expect(dry.candidates).toBe(7);
		expect(applied.deleted).toBe(7);
		expect((leg.left as Counts).total).toBe(0);
	});

	test('an abort stops between batches: what committed stands, the rest is intact', () => {
		const leg = value('abort');
		const applied = leg.applied as LedgerReport;
		expect(applied.detail.stopped).toBe('aborted');
		expect(applied.deleted).toBeGreaterThan(0);
		expect(applied.deleted).toBeLessThan(12);
		expect(applied.deleted % 4).toBe(0);
		expect((leg.left as Counts).total).toBe(12 - applied.deleted);
	});

	test('the matrix_activity prune completes under a real statement ceiling and spares fresh rows', () => {
		const leg = value('activity_ceiling');
		const before = leg.before as { aged: number; fresh: number };
		const after = leg.after as { aged: number; fresh: number };
		const applied = leg.applied as { deleted: number; batches: number; batchRows: number };
		expect(before).toEqual({ aged: 12, fresh: 1 });
		expect(applied.batchRows).toBe(4);
		expect(applied.batches).toBeGreaterThanOrEqual(4);
		expect(applied.deleted).toBeGreaterThanOrEqual(12);
		expect(after).toEqual({ aged: 0, fresh: 1 });
	});
});
